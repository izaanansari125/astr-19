# Sum of two floating point numbers
a = 2.5
b = 3.5
print("a + b =", a + b)
print("Type:", type(a + b))

# Difference between two integers
x = 10
y = 4
print("x - y =", x - y)
print("Type:", type(x - y))

# Product of a floating point number and an integer
m = 2.0
n = 5
print("m * n =", m * n)
print("Type:", type(m * n))
